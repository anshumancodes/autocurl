func TestGenerateEmptyUsesDefaultBaseURL(t *testing.T) {
	got, err := generator.Generate(nil, generator.Options{ProjectName: "empty"})
	if err != nil {
		t.Fatal(err)
	}
	want := "# Generated by autocurl\n# Project: empty\n\n@baseUrl = http://localhost:3000\n"
	if got != want {
		t.Fatalf("got %q, want %q", got, want)
	}
}

func TestGenerateMethodsParametersSourcesAndOrdering(t *testing.T) {
	routes := []discovery.Route{
		{Method: "POST", Path: "/users", Source: discovery.SourceLocation{File: "src/users.ts", Line: 30}},
		{Method: "GET", Path: "/", Source: discovery.SourceLocation{File: "src/root.ts", Line: 4}},
		{Method: "GET", Path: "/users/{id}/posts/{postId}", Source: discovery.SourceLocation{File: "src/users.ts", Line: 12}},
		{Method: "DELETE", Path: "/users/{id}", Source: discovery.SourceLocation{File: "src/users.ts", Line: 20}},
	}
	got, err := generator.Generate(routes, generator.Options{ProjectName: "example-api"})
	if err != nil {
		t.Fatal(err)
	}
	want := "# Generated by autocurl\n# Project: example-api\n\n@baseUrl = http://localhost:3000\n\n" +
		"### 1. GET /\n# @source src/root.ts:4\nGET {{baseUrl}}/\nAccept: application/json\n\n" +
		"### 2. POST /users\n# @source src/users.ts:30\nPOST {{baseUrl}}/users\nAccept: application/json\n\n" +
		"### 3. DELETE /users/{id}\n# @source src/users.ts:20\nDELETE {{baseUrl}}/users/{{id}}\nAccept: application/json\n\n" +
		"### 4. GET /users/{id}/posts/{postId}\n# @source src/users.ts:12\nGET {{baseUrl}}/users/{{id}}/posts/{{postId}}\nAccept: application/json\n"
	if got != want {
		t.Fatalf("got:\n%s\nwant:\n%s", got, want)
	}
}

func TestGenerateRelativeSourcesCustomBaseAndMissingSource(t *testing.T) {
	root := t.TempDir()
	routes := []discovery.Route{
		{Method: "GET", Path: "/health"},
		{Method: "GET", Path: "/users", Source: discovery.SourceLocation{File: filepath.Join(root, "src", "users.ts")}},
	}
	got, err := generator.Generate(routes, generator.Options{ProjectName: "api", ProjectRoot: root, BaseURL: "https://example.test/api/"})
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(got, "@baseUrl = https://example.test/api\n") || !strings.Contains(got, "# @source src/users.ts\n") {
		t.Fatalf("unexpected output:\n%s", got)
	}
	if strings.Contains(got, "@source \n") {
		t.Fatalf("missing source should not emit metadata:\n%s", got)
	}
}

func TestGenerateDeterministicAndDoesNotMutateInput(t *testing.T) {
	routes := []discovery.Route{
		{Method: "GET", Path: "/z"},
		{Method: "POST", Path: "/a"},
	}
	original := append([]discovery.Route(nil), routes...)
	one, err := generator.Generate(routes, generator.Options{ProjectName: "api"})
	if err != nil {
		t.Fatal(err)
	}
	two, err := generator.Generate(routes, generator.Options{ProjectName: "api"})
	if err != nil || one != two {
		t.Fatalf("not deterministic: err=%v first=%q second=%q", err, one, two)
	}
	if !reflect.DeepEqual(routes, original) {
		t.Fatalf("input mutated: got=%#v want=%#v", routes, original)
	}
}

func TestGenerateRejectsUnsafeMetadataAndBaseURL(t *testing.T) {
	cases := []struct {
		name    string
		options generator.Options
		routes  []discovery.Route
	}{
		{name: "project", options: generator.Options{ProjectName: "api\n### injected"}},
		{name: "source", options: generator.Options{ProjectName: "api"}, routes: []discovery.Route{{Method: "GET", Path: "/", Source: discovery.SourceLocation{File: "src\napi.ts"}}}},
		{name: "base url", options: generator.Options{ProjectName: "api", BaseURL: "http://localhost:3000\nGET /injected"}},
		{name: "invalid scheme", options: generator.Options{ProjectName: "api", BaseURL: "localhost:3000"}},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if _, err := generator.Generate(tc.routes, tc.options); err == nil {
				t.Fatal("expected error")
			}
		})
	}
}

func TestGenerateFromExpressDiscovery(t *testing.T) {
	root := fixtureProject(t, map[string]string{
		"package.json": `{"dependencies":{"express":"5.0.0"}}`,
		"server.js":    "const express = require('express');\nconst app = express();\napp.get('/users/:id', handler);\n",
	})
	result, err := discovery.Discover(root, discovery.DiscoverOptions{Extractors: []discovery.Extractor{express.New()}})
	if err != nil {
		t.Fatal(err)
	}
	got, err := generator.Generate(result.Routes, generator.Options{ProjectName: "express-api", ProjectRoot: root})
	t.Logf("\nGenerated Express .autocurl:\n%s", got)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(got, "### 1. GET /users/{id}\n") || !strings.Contains(got, "GET {{baseUrl}}/users/{{id}}\n") || !strings.Contains(got, "# @source server.js:3\n") {
		t.Fatalf("unexpected generated Express text:\n%s", got)
		t.Logf("\nGenerated Express .autocurl:\n%s", got)
	}
}

func TestGenerateFromNestJSDiscovery(t *testing.T) {
	root := fixtureProject(t, map[string]string{
		"package.json":            `{"dependencies":{"@nestjs/core":"^10.0.0"}}`,
		"tsconfig.json":           `{}`,
		"src/users.controller.ts": "import { Controller, Get, Post } from '@nestjs/common';\n@Controller('users')\nexport class Users { @Get(':id') find() {} @Post() create() {} }",
	})
	result, err := discovery.Discover(root, discovery.DiscoverOptions{Extractors: []discovery.Extractor{nestjs.New()}})
	if err != nil {
		t.Fatal(err)
	}
	got, err := generator.Generate(result.Routes, generator.Options{ProjectName: "nest-api", ProjectRoot: root})
	t.Logf("\nGenerated NestJS .autocurl:\n%s", got)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(got, "### 1. POST /users\n") || !strings.Contains(got, "### 2. GET /users/{id}\n") || !strings.Contains(got, "GET {{baseUrl}}/users/{{id}}\n") {
		t.Fatalf("unexpected generated NestJS text:\n%s", got)
	}
}

func fixtureProject(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for name, contents := range files {
		path := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(contents), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return root
}
