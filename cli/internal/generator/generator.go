// Package generator serializes normalized discovery routes into autocurl V1
// request-file text.
package generator

import (
	"errors"
	"fmt"
	"net/url"
	"path/filepath"
	"sort"
	"strings"
	"unicode"

	"github.com/anshumancodes/autocurl/internal/discovery"
)

var (
	ErrInvalidBaseURL = errors.New("invalid base URL")
	ErrUnsafeMetadata = errors.New("unsafe metadata")
	ErrInvalidRoute   = errors.New("invalid route")
)

// Options controls V1 request-file generation.
type Options struct {
	ProjectName string
	ProjectRoot string
	BaseURL     string
}

// Generate returns deterministic autocurl V1 request-file text for routes.
// The routes slice is never modified.
func Generate(routes []discovery.Route, options Options) (string, error) {
	baseURL, err := normalizeBaseURL(options.BaseURL)
	if err != nil {
		return "", err
	}
	if err := validateMetadata("project name", options.ProjectName); err != nil {
		return "", err
	}

	sortedRoutes := append([]discovery.Route(nil), routes...)
	for _, route := range sortedRoutes {
		if err := validateRoute(route); err != nil {
			return "", err
		}
		if err := validateMetadata("source file", route.Source.File); err != nil {
			return "", err
		}
	}
	sort.Slice(sortedRoutes, func(i, j int) bool {
		return routeKey(sortedRoutes[i]) < routeKey(sortedRoutes[j])
	})

	var output strings.Builder
	fmt.Fprintf(&output, "# Generated by autocurl\n# Project: %s\n\n@baseUrl = %s\n", options.ProjectName, baseURL)
	for index, route := range sortedRoutes {
		output.WriteString("\n### ")
		fmt.Fprintf(&output, "%d. %s %s\n", index+1, route.Method, route.Path)
		if source := sourceText(route, options.ProjectRoot); source != "" {
			fmt.Fprintf(&output, "# @source %s\n", source)
		}
		fmt.Fprintf(&output, "%s%s\nAccept: application/json\n", route.Method, requestURL(route.Path))
	}
	return output.String(), nil
}

func normalizeBaseURL(raw string) (string, error) {
	if err := validateMetadata("base URL", raw); err != nil {
		return "", err
	}
	raw = strings.TrimSpace(raw)
	if raw == "" {
		raw = "http://localhost:3000"
	}
	parsed, err := url.Parse(raw)
	if err != nil || parsed.Scheme == "" || parsed.Host == "" || parsed.User != nil || parsed.RawQuery != "" || parsed.Fragment != "" || (parsed.Scheme != "http" && parsed.Scheme != "https") {
		return "", fmt.Errorf("%w: %q", ErrInvalidBaseURL, raw)
	}
	return strings.TrimRight(parsed.String(), "/"), nil
}

func validateRoute(route discovery.Route) error {
	if _, ok := validMethods[route.Method]; !ok {
		return fmt.Errorf("%w: unsupported method %q", ErrInvalidRoute, route.Method)
	}
	if route.Path == "" || !strings.HasPrefix(route.Path, "/") {
		return fmt.Errorf("%w: path %q", ErrInvalidRoute, route.Path)
	}
	if strings.ContainsAny(route.Path, "?#\\") {
		return fmt.Errorf("%w: unsafe path %q", ErrInvalidRoute, route.Path)
	}
	for _, r := range route.Path {
		if unicode.IsControl(r) || unicode.IsSpace(r) {
			return fmt.Errorf("%w: unsafe path %q", ErrInvalidRoute, route.Path)
		}
	}
	if route.Source.Line < 0 {
		return fmt.Errorf("%w: negative source line %d", ErrInvalidRoute, route.Source.Line)
	}
	return nil
}

func validateMetadata(name, value string) error {
	for _, r := range value {
		if unicode.IsControl(r) {
			return fmt.Errorf("%w: %s contains control characters", ErrUnsafeMetadata, name)
		}
	}
	return nil
}

var validMethods = map[string]struct{}{
	"CONNECT": {}, "DELETE": {}, "GET": {}, "HEAD": {}, "OPTIONS": {},
	"PATCH": {}, "POST": {}, "PUT": {}, "TRACE": {},
}

func routeKey(route discovery.Route) string {
	return strings.Join([]string{
		route.Path, route.Method, route.Source.File, fmt.Sprintf("%020d", route.Source.Line),
		route.Language, route.Framework, string(route.Strategy), fmt.Sprintf("%020.10f", route.Confidence),
	}, "\x00")
}

func requestURL(path string) string {
	return " {{baseUrl}}" + parameterPlaceholders(path)
}

func parameterPlaceholders(path string) string {
	parts := strings.Split(path, "/")
	for i, part := range parts {
		if len(part) > 2 && strings.HasPrefix(part, "{") && strings.HasSuffix(part, "}") {
			parts[i] = "{{" + part[1:len(part)-1] + "}}"
		}
	}
	return strings.Join(parts, "/")
}

func sourceText(route discovery.Route, projectRoot string) string {
	if route.Source.File == "" {
		return ""
	}
	file := route.Source.File
	if projectRoot != "" && filepath.IsAbs(file) {
		if relative, err := filepath.Rel(projectRoot, file); err == nil {
			file = relative
		}
	}
	file = filepath.ToSlash(filepath.Clean(file))
	if route.Source.Line > 0 {
		return fmt.Sprintf("%s:%d", file, route.Source.Line)
	}
	return file
}
